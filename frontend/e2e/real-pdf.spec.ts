import {test,expect} from '@playwright/test'
test('private real PDF imports and navigates image and final question',async({page})=>{
 test.skip(!process.env.SAMPLE_PDF,'SAMPLE_PDF is required; private PDF never committed')
 await page.goto('/')
 await page.getByRole('button',{name:'试卷库',exact:true}).click()
 await page.locator('input[type=file]').setInputFiles(process.env.SAMPLE_PDF!)
 await expect(page.getByText('40 页 · 130 题',{exact:false})).toBeVisible()
 await page.getByRole('button',{name:'进入复盘工作台'}).click()
 await page.locator('.question-grid button').filter({hasText:/^81/}).click()
 await expect(page.locator('.editor h2')).toContainText('81')
 await expect(page.locator('.viewer input').first()).toHaveValue('25')
 await expect.poll(()=>page.locator('canvas').evaluate((c:any)=>c.width)).toBeGreaterThan(0)
 await expect(page.locator('canvas')).toHaveAttribute('data-rendered-page','25')
 await expect(page.locator('.viewer [role=alert]')).toHaveCount(0)
 await expect.poll(()=>page.locator('.editor .el-checkbox').count()).toBeGreaterThan(20)
 await page.screenshot({path:'../data/real-question81.png',fullPage:true})
 await page.locator('.question-grid button').filter({hasText:/^130/}).click()
 await expect(page.locator('.viewer input').first()).toHaveValue('39')
 await page.locator('.viewer').getByRole('button',{name:'下一页',exact:true}).click()
 await expect(page.locator('.viewer input').first()).toHaveValue('40')
 await expect(page.locator('canvas')).toHaveAttribute('data-rendered-page','40')
})
